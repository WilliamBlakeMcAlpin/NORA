// Vectorization check: render the traced logo at source size, compare it
// pixel by pixel with refs/logo/nora-logo-black.jpg, and write:
//   src/assets/logo/check/overlay.svg   trace outlines, for laying over the source
//   src/assets/logo/check/diff.png      difference map (bright = mismatch)
//   src/assets/logo/check/check.js      numbers for the D2 check page
//   output/D2/vector-check.json
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const parts = JSON.parse(fs.readFileSync(path.join(root, 'src/assets/logo/parts/manifest.json'), 'utf8'));
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'src/tokens/tokens.json'), 'utf8'));
const outDir = path.join(root, 'src/assets/logo/check');
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(path.join(root, 'output/D2'), { recursive: true });

const W = 862, H = 912;
const r = { x: 417 - 229 / 2, y: 508.5, w: 229, h: 1 };
const fills = ['monogram', 'wordmark', 'descriptor'].map((k) => `<path fill-rule="evenodd" d="${parts[k].d}"/>`).join('');
const traceSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
  `<rect width="${W}" height="${H}" fill="#0a0a0a"/><g fill="#fff">${fills}</g>` +
  `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="#fff" fill-opacity="${tokens.logo.rule_opacity_on_screen}"/></svg>`;
fs.writeFileSync(path.join(outDir, 'trace-render.svg'), traceSvg);
fs.writeFileSync(path.join(outDir, 'overlay.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><g fill="none" stroke="#9000FF" stroke-width="0.35">` +
  ['monogram', 'wordmark', 'descriptor'].map((k) => `<path d="${parts[k].d}"/>`).join('') + '</g></svg>');

const exe = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const browser = await chromium.launch(fs.existsSync(exe) ? { executablePath: exe } : {});
const page = await browser.newPage();
const toData = (p, mime) => `data:${mime};base64,` + fs.readFileSync(p).toString('base64');
const result = await page.evaluate(async ({ src, trace, W, H }) => {
  const load = (u) => new Promise((res) => { const i = new Image(); i.onload = () => res(i); i.src = u; });
  const [a, b] = await Promise.all([load(src), load(trace)]);
  const px = (img) => { const c = new OffscreenCanvas(W, H); const g = c.getContext('2d'); g.drawImage(img, 0, 0, W, H); return g.getImageData(0, 0, W, H).data; };
  const A = px(a), B = px(b);
  const regions = { monogram: [300, 200, 535, 478], wordmark: [305, 542, 529, 614], descriptor: [312, 682, 522, 703], rule: [300, 505, 545, 514] };
  const stats = {};
  const diff = new OffscreenCanvas(W, H); const dg = diff.getContext('2d'); const D = dg.createImageData(W, H);
  for (let i = 0; i < W * H; i++) { const d = Math.abs(A[i * 4] - B[i * 4]); D.data[i * 4] = D.data[i * 4 + 1] = D.data[i * 4 + 2] = Math.min(255, d * 2); D.data[i * 4 + 3] = 255; }
  dg.putImageData(D, 0, 0);
  for (const [k, [x0, y0, x1, y1]] of Object.entries(regions)) {
    let sum = 0, n = 0, big = 0, inkA = 0, inkB = 0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      const i = (y * W + x) * 4; const d = Math.abs(A[i] - B[i]);
      sum += d; n++; if (d > 96) big++; inkA += (A[i] - 10) / 245; inkB += (B[i] - 10) / 245;
    }
    stats[k] = { meanDiff: +(sum / n).toFixed(2), strongMismatchPx: big, inkAreaSource: Math.round(inkA), inkAreaTrace: Math.round(inkB), areaDeltaPct: +((inkB - inkA) / inkA * 100).toFixed(1) };
  }
  const blob = await diff.convertToBlob({ type: 'image/png' });
  const buf = new Uint8Array(await blob.arrayBuffer());
  return { stats, diff: Array.from(buf) };
}, { src: toData(path.join(root, 'refs/logo/nora-logo-black.jpg'), 'image/jpeg'), trace: toData(path.join(outDir, 'trace-render.svg'), 'image/svg+xml'), W, H });
await browser.close();

fs.writeFileSync(path.join(outDir, 'diff.png'), Buffer.from(result.diff));
fs.writeFileSync(path.join(outDir, 'check.js'), '// GENERATED by scripts/check-trace.mjs\nwindow.NORA_TRACE_CHECK = ' + JSON.stringify(result.stats, null, 1) + ';\n');
fs.writeFileSync(path.join(root, 'output/D2/vector-check.json'), JSON.stringify(result.stats, null, 1));
console.log('check: trace vs source');
for (const [k, s] of Object.entries(result.stats)) console.log(`  ${k.padEnd(11)} mean diff ${String(s.meanDiff).padStart(5)}/255  strong-mismatch px ${String(s.strongMismatchPx).padStart(4)}  ink area ${s.areaDeltaPct >= 0 ? '+' : ''}${s.areaDeltaPct}%`);
