// tokens.json -> tokens.css (CSS custom properties + @font-face) and tokens.js
// (the same data plus a computed contrast table, for pages to read on file://).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'src/tokens');
const t = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'));

// WCAG 2.x relative luminance and contrast ratio.
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const verdict = (r) => (r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'Large text / accents only' : 'Fail: do not use for text');

const textColors = ['white', 'ash', 'stone', 'violet', 'violet-royal-a', 'violet-royal-b', 'black'];
const grounds = ['black', 'white'];
const contrast = [];
for (const bg of grounds) for (const fg of textColors) {
  if (fg === bg) continue;
  const r = ratio(t.color[fg].hex, t.color[bg].hex);
  contrast.push({ fg, bg, ratio: Math.round(r * 100) / 100, verdict: verdict(r) });
}

const css = [];
css.push('/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit. */');
// Static instances (scripts/build-fonts.py): they embed in PDFs as TrueType,
// where the variable fonts would become Type 3.
const fonts = [
  ['Cormorant Garamond', 'CormorantGaramond', 'normal', [300, 400, 500]],
  ['Cormorant Garamond', 'CormorantGaramond-Italic', 'italic', [300, 400]],
  ['Jost', 'Jost', 'normal', [400, 500]],
];
for (const [fam, stem, style, weights] of fonts) for (const w of weights) {
  css.push(`@font-face { font-family: '${fam}'; font-style: ${style}; font-weight: ${w}; font-display: block;
  src: url('../assets/fonts/static/${stem}-${w}.woff2') format('woff2'), url('../assets/fonts/static/${stem}-${w}.ttf') format('truetype'); }`);
}
css.push(':root {');
for (const [k, v] of Object.entries(t.color)) css.push(`  --nora-${k}: ${v.hex};`);
for (const [k, v] of Object.entries(t.leopard)) if (v.startsWith?.('#')) css.push(`  --nora-leopard-${k}: ${v};`);
css.push(`  --font-editorial: ${t.font.editorial.stack};`);
css.push(`  --font-functional: ${t.font.functional.stack};`);
for (const [k, v] of Object.entries(t.weight)) css.push(`  --weight-${k}: ${v};`);
for (const [k, v] of Object.entries(t.tracking)) css.push(`  --tracking-${k}: ${v};`);
for (const [k, v] of Object.entries(t.leading)) css.push(`  --leading-${k}: ${v};`);
for (const [k, v] of Object.entries(t.space)) css.push(`  --space-${k}: ${v};`);
for (const [k, v] of Object.entries(t.line)) if (!v.includes('confirm')) css.push(`  --line-${k}: ${v};`);
for (const [medium, scale] of Object.entries(t.type)) {
  for (const [k, v] of Object.entries(scale)) if (typeof v === 'object') css.push(`  --type-${medium}-${k}: ${v.size};`);
}
css.push(`  --logo-rule-opacity: ${t.logo.rule_opacity_on_screen};`);
css.push('}');

fs.writeFileSync(path.join(dir, 'tokens.css'), css.join('\n') + '\n');
fs.writeFileSync(path.join(dir, 'tokens.js'),
  '// GENERATED by scripts/build-tokens.mjs. Do not edit.\nwindow.NORA_TOKENS = ' +
  JSON.stringify({ ...t, contrast }, null, 1) + ';\n');
console.log('tokens: wrote tokens.css, tokens.js');
for (const c of contrast) console.log(`  ${c.fg.padEnd(15)} on ${c.bg.padEnd(6)} ${c.ratio.toFixed(2).padStart(5)}:1  ${c.verdict}`);
