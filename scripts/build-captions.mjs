// src/content/instagram-captions.json -> captions.js (for the pages) and output/D8/captions.md (to copy and paste).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const c = JSON.parse(fs.readFileSync(path.join(root, 'src/content/instagram-captions.json'), 'utf8'));
fs.writeFileSync(path.join(root, 'src/content/captions.js'), '// GENERATED by scripts/build-captions.mjs\nwindow.NORA_CAPTIONS = ' + JSON.stringify(c, null, 1) + ';\n');

const md = ['# NORA Instagram captions', '', `> ${c.note}`, '', `**Handle:** ${c.handle}`, '', '**Bio:**', '', '```', c.bio, '```', '', '## Feed (posting order)', ''];
for (const p of c.feed) {
  md.push(`### ${p.post}`, '', p.caption, '', `*Alt text:* ${p.alt}`);
  if (p.check) md.push('', `*Check:* ${p.check}`);
  md.push('');
}
md.push('## Stories', '');
for (const s of c.stories) md.push(`- **${s.story}:** ${s.text}`);
md.push('', '## Highlight names', '', c.highlights.map((h) => `- ${h}`).join('\n'), '');
fs.mkdirSync(path.join(root, 'output/D8'), { recursive: true });
fs.writeFileSync(path.join(root, 'output/D8/captions.md'), md.join('\n'));
console.log('captions: wrote captions.js, output/D8/captions.md');
